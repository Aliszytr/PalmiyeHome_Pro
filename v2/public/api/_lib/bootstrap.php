<?php
/**
 * Palmiye Home V2 — shared server helpers (secrets, private data directory, settings).
 *
 * Secrets (Telegram token, iCal feed URLs, owner password hash, GeoIP paths) are read ONLY
 * from one file outside the web root:
 *   1. the path in the PALMIYE_SECRETS_FILE environment variable, or
 *   2. <parent of document root>/palmiye-secrets/.env.php
 * A secret file inside the document root is refused. Template: v2/deploy/palmiye-secrets/env.example.php
 *
 * This directory is not web-accessible (api/_lib/.htaccess). Compatible with PHP 7.0+.
 */

if (!defined('PALMIYE_LIB')) {
    define('PALMIYE_LIB', __DIR__);
}

/** Document root, or — for CLI/cron — the public directory this file is deployed in. */
function palmiye_doc_root()
{
    if (!empty($_SERVER['DOCUMENT_ROOT'])) {
        $r = realpath($_SERVER['DOCUMENT_ROOT']);
        if ($r) {
            return $r;
        }
    }
    return realpath(dirname(dirname(__DIR__))); // …/public_html/api/_lib → …/public_html
}

/** Loads the secret file once. Returns its real path, or false when missing / unsafe. */
function palmiye_load_secrets()
{
    static $loaded = null;
    if ($loaded !== null) {
        return $loaded;
    }
    $docRoot = palmiye_doc_root();
    $file = getenv('PALMIYE_SECRETS_FILE');
    if (!$file && $docRoot) {
        $file = dirname($docRoot) . '/palmiye-secrets/.env.php';
    }
    $real = $file ? realpath($file) : false;
    if (!$real || !is_readable($real)) {
        return $loaded = false;
    }
    if ($docRoot && strpos($real, $docRoot . DIRECTORY_SEPARATOR) === 0) {
        error_log('[Palmiye] Refused: secret file is inside the document root.');
        return $loaded = false;
    }
    require_once $real;
    return $loaded = $real;
}

/** A constant from the secret file, or '' when absent / still a placeholder. */
function palmiye_secret($name)
{
    if (!defined($name)) {
        return '';
    }
    $v = (string) constant($name);
    return (strpos($v, '_HERE') !== false) ? '' : $v;
}

/** Private, writable directory next to the secret file (never inside the web root). */
function palmiye_data_dir($sub)
{
    $secret = palmiye_load_secrets();
    if (!$secret) {
        return false;
    }
    $dir = dirname($secret) . '/' . $sub;
    if (!is_dir($dir) && !@mkdir($dir, 0700, true)) {
        return false;
    }
    return is_writable($dir) ? $dir : false;
}

/** Non-secret settings generated by v2/tools/build_site.py from config/site-config.json. */
function palmiye_settings()
{
    static $s = null;
    if ($s === null) {
        $s = json_decode((string) @file_get_contents(PALMIYE_LIB . '/settings.json'), true);
        if (!is_array($s)) {
            $s = array();
        }
    }
    return $s;
}

/** Atomic JSON write (temp file + rename). */
function palmiye_write_json($path, $data)
{
    $tmp = $path . '.' . getmypid() . '.tmp';
    if (@file_put_contents($tmp, json_encode($data), LOCK_EX) === false) {
        return false;
    }
    return @rename($tmp, $path);
}

function palmiye_read_json($path)
{
    $d = json_decode((string) @file_get_contents($path), true);
    return is_array($d) ? $d : null;
}
